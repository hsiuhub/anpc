// Lab1 ISR code
//
#pragma FUNC_ALWAYS_INLINE(isr1_RunLab1)
static inline void isr1_RunLab1(void)
{
    //
    // Read ADC sampled voltage and current values
    //
    phyvalue_ReadVoltageCurrentValues();

    PhyValue.IA.avg_pu = PhyValue.IA.raw_pu;
    PhyValue.IB.avg_pu = PhyValue.IB.raw_pu;
    PhyValue.IC.avg_pu = PhyValue.IC.raw_pu;

    //
    // Clear the PWM trips.
    //
    if(StateFlag.bits.pwm_kickoff == 1)
    {
        StateFlag.bits.pwm_kickoff = 0;
        pwm_mid_ClearAllPWMTrips();
    }

    if (StateFlag.bits.control_en == 1)
    {
        StateFlag.bits.control_en = 0;
        ctrl_Update3phasePWM(VICtrl.Duty_A, VICtrl.Duty_B, VICtrl.Duty_C,
                             VICtrl.Duty_A_prev, VICtrl.Duty_B_prev, VICtrl.Duty_C_prev);

        VICtrl.Duty_A_prev = VICtrl.Duty_A;
        VICtrl.Duty_B_prev = VICtrl.Duty_B;
        VICtrl.Duty_C_prev = VICtrl.Duty_C;
    }


    isr_mid_ClearPWMInterruptFlag(ISR_MID_ISR1_TRIG_BASE);
}

//
// Lab2 ISR code, no PLL, V/Hz control. No current control loop
//
#pragma FUNC_ALWAYS_INLINE(isr1_RunLab2)
static inline void isr1_RunLab2(void)
{
    //
    // Read ADC sampled voltage and current values
    //
    phyvalue_ReadVoltageCurrentValues();

    PhyValue.IA.avg_pu = PhyValue.IA.raw_pu;
    PhyValue.IB.avg_pu = PhyValue.IB.raw_pu;
    PhyValue.IC.avg_pu = PhyValue.IC.raw_pu;

    //
    // Clear the PWM trips when.
    //
    if(StateFlag.bits.pwm_kickoff == 1)
    {
        StateFlag.bits.pwm_kickoff = 0;
        pwm_mid_ClearAllPWMTrips();
        StateFlag.bits.control_en = 1;
    }

    if (StateFlag.bits.control_en == 1)
    {
        //
        // When grid is not connected, generate
        // internal phase reference
        //
        ctrl_GenerateInternalReference();

        //
        // Since this is Open-loop configuration, DQ values
        // generated by internal reference can be directly used
        // for generating 3-phase PWM duty values
        //
        VICtrl.Vd_pu = ANPC_VREF_DEFAULT;
        VICtrl.Vq_pu = 0;
        VICtrl.Vz_pu = 0;
        DQ0_ABC_run(&VICtrl.Vabc_pu, VICtrl.Vd_pu, VICtrl.Vq_pu, VICtrl.Vz_pu, Spll.sine, Spll.cosine);

        VICtrl.Duty_A = VICtrl.Vabc_pu.a;
        VICtrl.Duty_B = VICtrl.Vabc_pu.b;
        VICtrl.Duty_C = VICtrl.Vabc_pu.c;

        ctrl_Update3phasePWM(VICtrl.Duty_A, VICtrl.Duty_B, VICtrl.Duty_C,
                             VICtrl.Duty_A_prev, VICtrl.Duty_B_prev, VICtrl.Duty_C_prev);

        //
        // Run the SPLL module
        //
        ctrl_RunSPLL();

        //
        // Based on theta estimated by SPLL, compute sine and cosine
        //
        Spll.sine = sinf(Spll.angle_radians);
        Spll.cosine = cosf(Spll.angle_radians);
    }

    isr_mid_ClearPWMInterruptFlag(ISR_MID_ISR1_TRIG_BASE);
}

//
// Lab3 ISR code - No grid connection. I/Hz control for Inverter. Current control loop
// Use resistor load for inverter running in current control only
//
#pragma FUNC_ALWAYS_INLINE(isr1_RunLab3)
static inline void isr1_RunLab3(void)
{
    //
    // Read ADC sampled voltage and current values
    //
    phyvalue_ReadVoltageCurrentValues();

    PhyValue.IA.avg_pu = PhyValue.IA.raw_pu;
    PhyValue.IB.avg_pu = PhyValue.IB.raw_pu;
    PhyValue.IC.avg_pu = PhyValue.IC.raw_pu;

    //
    // Transform the above feedback signals from ABC to DQ axes
    //
    ctrl_ABCtoDQ0_Transform();

    //
    // Clear the PWM trips.
    //
    if(StateFlag.bits.pwm_kickoff == 1)
    {
        StateFlag.bits.pwm_kickoff = 0;
        pwm_mid_ClearAllPWMTrips();
        StateFlag.bits.control_en = 1;
    }

    if(StateFlag.bits.control_en == 1)
    {
        //
        // When grid is not connected, generate
        // internal phase reference
        //
        ctrl_GenerateInternalReference();

        //
        // Run the current close loop
        //
        ctrl_RunCurrentLoop();

        //
        // Vd and Vq can be directly used
        // for generating 3-phase PWM duty values
        DQ0_ABC_run(&VICtrl.Vabc_pu, VICtrl.Vd_pu, VICtrl.Vq_pu, VICtrl.Vz_pu, Spll.sine, Spll.cosine);

        VICtrl.Duty_A = VICtrl.Vabc_pu.a;
        VICtrl.Duty_B = VICtrl.Vabc_pu.b;
        VICtrl.Duty_C = VICtrl.Vabc_pu.c;

        ctrl_Update3phasePWM(VICtrl.Duty_A, VICtrl.Duty_B, VICtrl.Duty_C,
                             VICtrl.Duty_A_prev, VICtrl.Duty_B_prev, VICtrl.Duty_C_prev);

        VICtrl.Duty_A_prev = VICtrl.Duty_A;
        VICtrl.Duty_B_prev = VICtrl.Duty_B;
        VICtrl.Duty_C_prev = VICtrl.Duty_C;

        //
        // Run the SPLL module
        //
        ctrl_RunSPLL();

        PhyValue.Vbus.raw_pu = PhyValue.Vbusp.raw_pu + PhyValue.Vbusn.raw_pu;
        if(PhyValue.Vbus.raw_pu <= 0) // avoid division by zero
        {
            PhyValue.Vbus.raw_pu = 0.001;
        }
        PhyValue.Vbus.raw = PhyValue.Vbus.raw_pu * ANPC_VBUS_MAX_SENSE;
        PhyValue.Vbus.avg = PHY_LOW_PASS_FILTER * (PhyValue.Vbus.avg - PhyValue.Vbus.raw) + PhyValue.Vbus.raw;


        // Middle point voltage control
        PhyValue.Vbus_delta.raw = (PhyValue.Vbusp.raw_pu - PhyValue.Vbusn.raw_pu) * ANPC_VBUS_MAX_SENSE;
        PhyValue.Vbus_delta.avg = 0.9981 * (PhyValue.Vbus_delta.avg - PhyValue.Vbus_delta.raw) + PhyValue.Vbus_delta.raw;

        //AVG of the voltage
        //
        // Based on theta estimated by SPLL, compute sine and cosine
        //
        Spll.sine = sinf(Spll.angle_radians);
        Spll.cosine = cosf(Spll.angle_radians);
    }

    isr_mid_ClearPWMInterruptFlag(ISR_MID_ISR1_TRIG_BASE);
}

//
// Lab4 ISR code. Inverter mode. PLL with grid connection (so current loop only)
//
//
#pragma FUNC_ALWAYS_INLINE(isr1_RunLab4)
static inline void isr1_RunLab4(void)
{
    //
    // Read ADC sampled voltage and current values
    //
    phyvalue_ReadVoltageCurrentValues();

    PhyValue.IA.avg_pu = PhyValue.IA.raw_pu;
    PhyValue.IB.avg_pu = PhyValue.IB.raw_pu;
    PhyValue.IC.avg_pu = PhyValue.IC.raw_pu;

    //
    // Transform the above feedback signals from ABC to DQ axes
    //
    ctrl_ABCtoDQ0_Transform();

    if(AcValue.ac_A.zcd)
    {
        if(StateFlag.bits.pwm_kickoff == 1)
        {
            StateFlag.bits.pwm_kickoff = 0;
            pwm_mid_ClearAllPWMTrips();
            StateFlag.bits.control_en = 1;
        }
    }

    if (StateFlag.bits.control_en == 1)
    {
        //
        // Run the current close loop
        //
        ctrl_RunCurrentLoop();

        //
        // Vd and Vq can be directly used
        // for generating 3-phase PWM duty values
        DQ0_ABC_run(&VICtrl.Vabc_pu, VICtrl.Vd_pu, VICtrl.Vq_pu, VICtrl.Vz_pu, Spll.sine, Spll.cosine);

        // Middle point voltage control loop plus space vector for Inverter mode********
        VICtrl.Vbus_delta_out = CTRL_GV_RUN(&VICtrl.Vbus_delta, PhyValue.Vbus_delta.avg, 0);

        ctrl_3rd_Harmonic_Injection();

        VICtrl.Duty_A = VICtrl.Vabc_pu.a + VICtrl.Vbus_delta_out + VICtrl.Duty_3rd;
        VICtrl.Duty_B = VICtrl.Vabc_pu.b + VICtrl.Vbus_delta_out + VICtrl.Duty_3rd;
        VICtrl.Duty_C = VICtrl.Vabc_pu.c + VICtrl.Vbus_delta_out + VICtrl.Duty_3rd;

        ctrl_Update3phasePWM(VICtrl.Duty_A, VICtrl.Duty_B, VICtrl.Duty_C, 0, 0, 0);

        //
        // Update dead-band slew for soft-start of PFC
        //
        if(VICtrl.Deadband > ANPC_CTRL_HIGH_FREQ_DEADBAND)
        {
            pwm_mid_UpdatePWMDeadBand(VICtrl.Deadband);
            VICtrl.Deadband = VICtrl.Deadband - ANPC_SOFTSTART_DEADBAND_SLEW;
        }
        else
        {
            VICtrl.Deadband = ANPC_CTRL_HIGH_FREQ_DEADBAND;
            pwm_mid_UpdatePWMDeadBand(VICtrl.Deadband);
        }

    }

    //
    // Run SPLL
    //
    ctrl_RunSPLL();

    // Middle point voltage control
    PhyValue.Vbus_delta.raw = (PhyValue.Vbusp.raw_pu - PhyValue.Vbusn.raw_pu) * ANPC_VBUS_MAX_SENSE;
    PhyValue.Vbus_delta.avg = 0.9981 * (PhyValue.Vbus_delta.avg - PhyValue.Vbus_delta.raw) + PhyValue.Vbus_delta.raw;

    //
    // Based on theta estimated by SPLL, compute sine and cosine
    //
    Spll.sine = sinf(Spll.angle_radians);
    Spll.cosine = cosf(Spll.angle_radians);

    isr_mid_ClearPWMInterruptFlag(ISR_MID_ISR1_TRIG_BASE);
}

