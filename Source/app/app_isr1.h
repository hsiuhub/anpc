//
// Lab6 ISR code. PFC voltage loop and current loop closed
//
#pragma FUNC_ALWAYS_INLINE(isr1_RunLab6)
static inline void isr1_RunLab6(void)
{
    //
    // Read ADC sampled voltage and current values
    //
    phyvalue_ReadVoltageCurrentValues();

    PhyValue.IA.avg_pu = PhyValue.IA.raw_pu;
    PhyValue.IB.avg_pu = PhyValue.IB.raw_pu;
    PhyValue.IC.avg_pu = PhyValue.IC.raw_pu;

    //
    // Transform the above feedback signals from ABC to DQ axes
    //
    ctrl_ABCtoDQ0_Transform();

    if (AcValue.ac_A.zcd)
    {
        if(StateFlag.bits.pwm_kickoff == 1)
        {
            StateFlag.bits.pwm_kickoff = 0;
            pwm_mid_ClearAllPWMTrips();
            StateFlag.bits.control_en = 1;
        }
    }

    if (StateFlag.bits.control_en == 1)
    {
        //
        // Run the current close loop
        //

        /* Voltage control loop */
        if (StateFlag.bits.soft_start_on == 1)
            VICtrl.Id_ref = VICtrl.Id_cmd; 
        else
            VICtrl.Id_ref = -1 * (CTRL_GV_RUN(&VICtrl.Vbus, VICtrl.Vbus_ref, PhyValue.Vbus.raw));

        /* Current control loop */
        ctrl_RunCurrentLoop();

        /* Middle point voltage control loop */
        VICtrl.Vbus_delta_out = CTRL_GV_RUN(&VICtrl.Vbus_delta, -PhyValue.Vbus_delta.avg, 0);

        /*
         * Vd and Vq can be directly used for generating 3-phase PWM duty values.
         */
        DQ0_ABC_run(&VICtrl.Vabc_pu, VICtrl.Vd_pu, VICtrl.Vq_pu, VICtrl.Vz_pu, Spll.sine, Spll.cosine);

        ctrl_3rd_Harmonic_Injection();

        /*
         * Constant duty has been added in the system in order to perturb the middle point of the converter.
         */
        VICtrl.Duty_A = VICtrl.Vabc_pu.a + VICtrl.Vbus_delta_out + 0;// VICtrl.Duty_3rd;
        VICtrl.Duty_B = VICtrl.Vabc_pu.b + VICtrl.Vbus_delta_out + 0;// VICtrl.Duty_3rd;
        VICtrl.Duty_C = VICtrl.Vabc_pu.c + VICtrl.Vbus_delta_out + 0;// VICtrl.Duty_3rd;


        ctrl_Update3phasePWM(VICtrl.Duty_A, VICtrl.Duty_B, VICtrl.Duty_C, 0, 0, 0);

        //
        // Update dead-band slew for soft-start of PFC
        //
        if(0)//VICtrl.Deadband > ANPC_CTRL_HIGH_FREQ_DEADBAND)
        {
            pwm_mid_UpdatePWMDeadBand(VICtrl.Deadband);
            VICtrl.Deadband = VICtrl.Deadband - ANPC_SOFTSTART_DEADBAND_SLEW;
        }
        else
        {
            VICtrl.Deadband = ANPC_CTRL_HIGH_FREQ_DEADBAND;
            pwm_mid_UpdatePWMDeadBand(VICtrl.Deadband);
        }

    }

    /* Run SPLL */
    ctrl_RunSPLL();

    /* AVG of the voltage */
    PhyValue.Vbus_delta.raw = (PhyValue.Vbusp.raw_pu - PhyValue.Vbusn.raw_pu) * ANPC_VBUS_MAX_SENSE;
    PhyValue.Vbus_delta.avg = 0.9981 * (PhyValue.Vbus_delta.avg - PhyValue.Vbus_delta.raw) + PhyValue.Vbus_delta.raw;

    /*
     * Based on theta estimated by SPLL, compute sine and cosine.
     */
    Spll.sine = sinf(Spll.angle_radians);
    Spll.cosine = cosf(Spll.angle_radians);

    isr_mid_ClearPWMInterruptFlag(ISR_MID_ISR1_TRIG_BASE);
}

#pragma FUNC_ALWAYS_INLINE(ISR1_Callback)
static inline void ISR1_Callback(void)
{

    #if ANPC_LAB == 1U
        isr1_RunLab1();

    #elif  ANPC_LAB == 2U //Inverter open loop, no PLL, V/Hz control. No current control loop
        isr1_RunLab2();

    #elif  ANPC_LAB == 3U // Inverter closed current loop without PLL (no grid connection. Resistive load)
        isr1_RunLab3();

    #elif  ANPC_LAB == 4U  // Inverter closed current loop with PLL (grid connected mode)
        isr1_RunLab4();

    #elif  ANPC_LAB == 5U // PFC Current loop with open voltage loop
        isr1_RunLab5();

    #elif  ANPC_LAB == 6U // PFC Voltage loop and Current loop closed
        isr1_RunLab6();

    #endif

}







